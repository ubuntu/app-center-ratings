@dataclass(frozen=True)
class RatingsAPI:
    """Python modules generated from the workload's actual protobuf definitions."""

    user_pb: ModuleType
    user_grpc: ModuleType
    app_pb: ModuleType
    app_grpc: ModuleType


@contextmanager
def generated_api() -> Iterator[RatingsAPI]:
    """Compile outside the checkout, and remove generated imports on exit."""
    proto_dir = Path(__file__).resolve().parents[2] / "ratings_rock" / "proto"
    builtin_dir = Path(grpc_tools.__file__).parent / "_proto"
    sources = sorted(proto_dir.glob("*.proto"))
    if not sources:
        raise RuntimeError("Ratings protobuf sources are missing")
    names = [f"{source.stem}{suffix}" for source in sources for suffix in ("_pb2", "_pb2_grpc")]
    if any(name in sys.modules for name in names):
        raise RuntimeError("Ratings protobuf modules were already imported")
    with tempfile.TemporaryDirectory(prefix="ratings-protobuf-") as directory:
        result = protoc.main(
            [
                "protoc",
                f"-I{proto_dir}",
                f"-I{builtin_dir}",
                f"--python_out={directory}",
                f"--grpc_python_out={directory}",
                *(str(source) for source in sources),
            ]
        )
        if result:
            raise RuntimeError(f"Ratings protobuf generation failed with exit code {result}")
        sys.path.insert(0, directory)
        try:
            yield RatingsAPI(
                user_pb=importlib.import_module("ratings_features_user_pb2"),
                user_grpc=importlib.import_module("ratings_features_user_pb2_grpc"),
                app_pb=importlib.import_module("ratings_features_app_pb2"),
                app_grpc=importlib.import_module("ratings_features_app_pb2_grpc"),
            )
        finally:
            sys.path.remove(directory)
            for name in names:
                sys.modules.pop(name, None)


def model_namespace(model: str | None) -> str:
    """Only accept a model generated by the pinned Jubilant temp_model helper."""
    namespace = (model or "").rsplit(":", 1)[-1].rsplit("/", 1)[-1]
    if not re.fullmatch(r"jubilant-[0-9a-f]{8}", namespace):
        raise ValueError("Integration tests require a fresh Jubilant temporary model")
    return namespace


def kubectl(model: str | None, *args: str) -> list[str]:
    """Use the provisioned local MicroK8s, never the user's kubectl context."""
    return ["microk8s", "kubectl", "--namespace", model_namespace(model), *args]


@contextmanager
def port_forward(model: str | None) -> Iterator[str]:
    """Forward service/ratings:8080 to a kernel-selected loopback port."""
    command = kubectl(
        model,
        "port-forward",
        f"service/{APP_NAME}",
        ":8080",
        "--address=127.0.0.1",
        "--pod-running-timeout=30s",
    )
    process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    try:
        assert process.stdout is not None
        deadline = time.monotonic() + 45
        output = bytearray()
        with selectors.DefaultSelector() as selector:
            selector.register(process.stdout, selectors.EVENT_READ)
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise RuntimeError("MicroK8s port-forward exited before becoming ready")
                if not selector.select(timeout=min(1, max(0, deadline - time.monotonic()))):
                    continue
                chunk = os.read(process.stdout.fileno(), 4096)
                if not chunk:
                    raise RuntimeError("MicroK8s port-forward closed its output before readiness")
                output.extend(chunk)
                match = re.search(rb"Forwarding from 127\.0\.0\.1:(\d+) -> 8080", output)
                if match:
                    target = f"127.0.0.1:{int(match[1])}"
                    break
                if len(output) > 65536:
                    raise RuntimeError("MicroK8s port-forward produced excessive startup output")
            else:
                raise TimeoutError("MicroK8s port-forward did not become ready within 45 seconds")
        yield target
    finally:
        # Always reap the child, including startup errors and failed gRPC assertions.
        if process.poll() is None:
            process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)
        finally:
            if process.stdout is not None:
                process.stdout.close()


def rpc(method, request, **kwargs):
    """Report just the status code, not gRPC details or authorization metadata."""
    __tracebackhide__ = True
    try:
        return method(request, timeout=RPC_TIMEOUT, **kwargs)
    except grpc.RpcError as error:
        raise AssertionError(f"Ratings RPC failed: {error.code().name}") from None


def smoke_rpcs(api: RatingsAPI, target: str, identifier: str) -> None:
    """Exercise identity creation, a database read without Snap Store traffic, and deletion."""
    __tracebackhide__ = True
    # The workload is plaintext; the forward only binds to loopback, not a public ingress.
    with grpc.insecure_channel(target) as channel:
        try:
            grpc.channel_ready_future(channel).result(timeout=30)
        except grpc.FutureTimeoutError:
            raise AssertionError("Ratings gRPC channel was not ready within 30 seconds") from None
        user = api.user_grpc.UserStub(channel)
        app = api.app_grpc.AppStub(channel)
        token = rpc(user.Authenticate, api.user_pb.AuthenticateRequest(id=identifier)).token
        if not token:
            raise AssertionError("Authenticate returned an empty JWT")
        metadata = (("authorization", f"Bearer {token}"),)
        try:
            # No votes exist for this random snap ID, so chart name resolution has nothing
            # to fetch from Snap Store. Do not call Vote or query real snap IDs here.
            response = rpc(
                app.GetBulkRatings,
                api.app_pb.GetBulkRatingsRequest(snap_ids=[identifier]),
                metadata=metadata,
            )
            if response.ratings:
                raise AssertionError("An unused snap ID unexpectedly returned ratings")
        finally:
            rpc(user.Delete, Empty(), metadata=metadata)


def diagnostics(juju: jubilant.Juju) -> None:
    """Best-effort per-test status summaries, with bounded calls and no log/secret dumps."""
    commands = {
        "juju": [juju.cli_binary, "status", "--model", juju.model, "--format=json"],
        "pods": kubectl(juju.model, "get", "pods", "--output=json", "--request-timeout=15s"),
    }
    for label, command in commands.items():
        try:
            result = subprocess.run(command, check=True, capture_output=True, text=True, timeout=20)
            data = json.loads(result.stdout)
            summary = status_summary(data) if label == "juju" else pod_summary(data)
            print(f"Integration {label}: {json.dumps(summary, sort_keys=True)}")
        except (OSError, subprocess.SubprocessError, ValueError, KeyError, TypeError) as error:
            # CalledProcessError.stdout/stderr and status messages can contain secrets.
            print(f"Integration {label} diagnostics unavailable: {type(error).__name__}")


def status_summary(data: dict) -> dict:
    """Include only state enums, not free-form workload messages or relation data."""
    return {
        name: {
            "status": app.get("application-status", {}).get("current"),
            "units": {
                unit_name: {
                    "workload": unit.get("workload-status", {}).get("current"),
                    "agent": unit.get("juju-status", {}).get("current"),
                }
                for unit_name, unit in app.get("units", {}).items()
            },
        }
        for name, app in data.get("applications", {}).items()
    }


def pod_summary(data: dict) -> dict:
    """Exclude pod specs, environment, event messages, and container logs."""
    return {
        pod["metadata"]["name"]: {
            "phase": pod.get("status", {}).get("phase"),
            "containers": {
                container["name"]: {
                    "ready": container.get("ready"),
                    "restarts": container.get("restartCount"),
                    "state": list(container.get("state", {})),
                }
                for container in pod.get("status", {}).get("containerStatuses", [])
            },
        }
        for pod in data.get("items", [])
    }
